def resolve_module(keypoint_name: str) -> tuple:
    """
    根据 keypoint 名称返回 (一级模块, 二级模块, 三级模块)
    如果未找到映射，返回 ('未知', '', keypoint_name) - 待用户补充
    """
    if keypoint_name in KEYPOINT_TO_MODULE:
        return KEYPOINT_TO_MODULE[keypoint_name]

    # 部分匹配：检查 keypoint 是否包含已知关键词
    for kp, mapping in KEYPOINT_TO_MODULE.items():
        if kp and (kp in keypoint_name or keypoint_name in kp):
            return mapping

    return ('未知', '', keypoint_name)


def build_question_link(exercise_key: str, question_id: str, routecs: str = "xingce") -> str:
    """
    构建单题链接（每个题目单独的链接）
    使用 URL fragment 锚定到具体题目
    """
    if not exercise_key or not question_id:
        return ""
    return f"https://spa.fenbi.com/ti/exam/solution/{exercise_key}?routecs={routecs}#question-{question_id}"